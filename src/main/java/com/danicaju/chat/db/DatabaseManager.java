    public Map<String, List<String>> updateReaction(long messageId, String emoji, String username, boolean add) {
        if (emoji == null || emoji.trim().isEmpty() || username == null) {
            return null;
        }
        String cleanEmoji = emoji.trim();
        if (cleanEmoji.length() > 16) {
            cleanEmoji = cleanEmoji.substring(0, 16);
        }
        String cleanUser = username.trim();

        synchronized (reactionLock) {
            Message msg = getMessageById(messageId);
            if (msg == null) {
                return null;
            }
            Map<String, List<String>> reactions = msg.getReactions() != null
                    ? new LinkedHashMap<>(msg.getReactions())
                    : new LinkedHashMap<>();

            List<String> users = reactions.computeIfAbsent(cleanEmoji, k -> new ArrayList<>());
            if (add) {
                boolean present = users.stream().anyMatch(u -> u.equalsIgnoreCase(cleanUser));
                if (!present) {
                    users.add(cleanUser);
                }
            } else {
                users.removeIf(u -> u.equalsIgnoreCase(cleanUser));
                if (users.isEmpty()) {
                    reactions.remove(cleanEmoji);
                }
            }

            String json = reactions.isEmpty() ? null : toJsonOrNull(reactions);
            try (Connection conn = pool.getConnection();
                 PreparedStatement ps = conn.prepareStatement("UPDATE messages SET reactions_json = ? WHERE id = ?")) {
                ps.setString(1, json);
                ps.setLong(2, messageId);
                ps.executeUpdate();
            } catch (SQLException e) {
                throw new IllegalStateException("Error actualizando reacción", e);
            }
            return reactions;
        }
    }

