    private void initSchema() {
        try (Connection conn = pool.getConnection(); Statement st = conn.createStatement()) {
            st.execute("""
                CREATE TABLE IF NOT EXISTS user_profiles (
                    username VARCHAR(64) PRIMARY KEY,
                    bio VARCHAR(300),
                    avatar VARCHAR(64),
                    banner VARCHAR(64),
                    avatar_image CLOB,
                    presence VARCHAR(20),
                    custom_status VARCHAR(120),
                    status_symbol VARCHAR(24),
                    role VARCHAR(32),
                    permissions BIGINT,
                    public_key CLOB,
                    updated_at BIGINT
                )
            """);

            st.execute("""
                CREATE TABLE IF NOT EXISTS channels (
                    name VARCHAR(64) PRIMARY KEY,
                    channel_type VARCHAR(16) NOT NULL,
                    topic VARCHAR(240),
                    created_by VARCHAR(64),
                    default_allow_mask BIGINT DEFAULT 0,
                    default_deny_mask BIGINT DEFAULT 0,
                    user_overrides_json CLOB,
                    created_at BIGINT
                )
            """);

            st.execute("""
                CREATE TABLE IF NOT EXISTS messages (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    temp_id VARCHAR(64),
                    msg_type VARCHAR(32) NOT NULL,
                    channel VARCHAR(64),
                    sender VARCHAR(64),
                    target VARCHAR(64),
                    content CLOB,
                    reply_to_id BIGINT,
                    reply_sender VARCHAR(64),
                    reply_preview VARCHAR(240),
                    thread_parent_id BIGINT,
                    reactions_json CLOB,
                    embed_json CLOB,
                    poll_json CLOB,
                    attachment_name VARCHAR(255),
                    attachment_base64 CLOB,
                    encrypted BOOLEAN DEFAULT FALSE,
                    iv VARCHAR(128),
                    sender_public_key CLOB,
                    created_at BIGINT NOT NULL
                )
            """);

            st.execute("CREATE INDEX IF NOT EXISTS idx_messages_channel_id ON messages(channel, id DESC)");
            st.execute("CREATE INDEX IF NOT EXISTS idx_messages_thread ON messages(thread_parent_id, id ASC)");

            st.execute("""
                CREATE TABLE IF NOT EXISTS webhooks (
                    id VARCHAR(64) PRIMARY KEY,
                    channel VARCHAR(64) NOT NULL,
                    name VARCHAR(80) NOT NULL,
                    token VARCHAR(128) NOT NULL,
                    created_by VARCHAR(64),
                    created_at BIGINT NOT NULL
                )
            """);
        } catch (SQLException e) {
            throw new IllegalStateException("Error inicializando el esquema de base de datos H2", e);
        }
    }

