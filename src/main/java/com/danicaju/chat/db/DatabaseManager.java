    public PollData votePoll(long messageId, int optionIndex, String username) {
        synchronized (pollLock) {
            Message msg = getMessageById(messageId);
            if (msg == null || msg.getPoll() == null) {
                return null;
            }
            PollData poll = msg.getPoll();
            poll.vote(optionIndex, username);
            try (Connection conn = pool.getConnection();
                 PreparedStatement ps = conn.prepareStatement("UPDATE messages SET poll_json = ? WHERE id = ?")) {
                ps.setString(1, toJsonOrNull(poll));
                ps.setLong(2, messageId);
                ps.executeUpdate();
            } catch (SQLException e) {
                throw new IllegalStateException("Error guardando voto de encuesta", e);
            }
            return poll;
        }
    }

    /**
     * Buscador avanzado con filtros from:, in:, has:link, has:file y texto libre.
     */
    public List<Message> searchMessages(String rawQuery, Set<String> accessibleChannels, String requestingUser) {
        SearchQueryParser parsed = SearchQueryParser.parse(rawQuery);
        List<Message> results = new ArrayList<>();

        StringBuilder sql = new StringBuilder("SELECT * FROM messages WHERE encrypted = FALSE ");
        List<Object> params = new ArrayList<>();

        if (parsed.fromUser() != null) {
            sql.append("AND LOWER(sender) = LOWER(?) ");
            params.add(parsed.fromUser());
        }
        if (parsed.inChannel() != null) {
            if (!accessibleChannels.contains(parsed.inChannel().toLowerCase(Locale.ROOT))) {
                return Collections.emptyList();
            }
            sql.append("AND LOWER(channel) = LOWER(?) ");
            params.add(parsed.inChannel());
        }
        if (parsed.hasFile()) {
            sql.append("AND attachment_base64 IS NOT NULL ");
        }
        if (parsed.hasLink()) {
            sql.append("AND (LOWER(content) LIKE '%http://%' OR LOWER(content) LIKE '%https://%' OR embed_json IS NOT NULL) ");
        }
        for (String term : parsed.textTerms()) {
            sql.append("AND (LOWER(COALESCE(content, '')) LIKE ? OR LOWER(COALESCE(embed_json, '')) LIKE ? OR LOWER(COALESCE(attachment_name, '')) LIKE ?) ");
            String like = "%" + term + "%";
            params.add(like);
            params.add(like);
            params.add(like);
        }
        sql.append("ORDER BY id DESC LIMIT 120");

        try (Connection conn = pool.getConnection();
             PreparedStatement ps = conn.prepareStatement(sql.toString())) {
            for (int i = 0; i < params.size(); i++) {
                ps.setObject(i + 1, params.get(i));
            }
            try (ResultSet rs = ps.executeQuery()) {
                while (rs.next()) {
                    Message m = mapMessage(rs);
                    if (m.getType() == MessageType.PRIVATE) {
                        boolean involved = requestingUser != null &&
                                (requestingUser.equalsIgnoreCase(m.getSender()) || requestingUser.equalsIgnoreCase(m.getTarget()));
                        if (!involved) {
                            continue;
                        }
                    } else if (m.getChannel() != null &&
                            !accessibleChannels.contains(m.getChannel().toLowerCase(Locale.ROOT))) {
                        continue;
                    }
                    results.add(m);
                    if (results.size() >= 50) {
                        break;
                    }
                }
            }
            return results;
        } catch (SQLException e) {
            throw new IllegalStateException("Error ejecutando búsqueda avanzada", e);
        }
    }

