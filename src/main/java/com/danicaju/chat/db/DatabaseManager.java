    public WebhookInfo createWebhook(String channel, String name, String createdBy) {
        String id = UUID.randomUUID().toString().replace("-", "").substring(0, 16);
        byte[] rawToken = new byte[24];
        RANDOM.nextBytes(rawToken);
        String token = Base64.getUrlEncoder().withoutPadding().encodeToString(rawToken);

        WebhookInfo info = new WebhookInfo(id, channel, name, token, createdBy);
        String sql = "INSERT INTO webhooks (id, channel, name, token, created_by, created_at) VALUES (?, ?, ?, ?, ?, ?)";
        try (Connection conn = pool.getConnection(); PreparedStatement ps = conn.prepareStatement(sql)) {
            ps.setString(1, info.getId());
            ps.setString(2, info.getChannel());
            ps.setString(3, info.getName());
            ps.setString(4, info.getToken());
            ps.setString(5, info.getCreatedBy());
            ps.setLong(6, info.getCreatedAt());
            ps.executeUpdate();
            return info;
        } catch (SQLException e) {
            throw new IllegalStateException("Error creando webhook", e);
        }
    }

