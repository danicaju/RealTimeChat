    private void populateThreadCounts(Connection conn, List<Message> messages) throws SQLException {
        if (messages.isEmpty()) return;
        Map<Long, Message> byId = new HashMap<>();
        StringBuilder placeholders = new StringBuilder();
        for (Message m : messages) {
            if (m.getId() != null) {
                byId.put(m.getId(), m);
                if (placeholders.length() > 0) placeholders.append(',');
                placeholders.append('?');
            }
        }
        if (byId.isEmpty()) return;

        String sql = "SELECT thread_parent_id, COUNT(*) AS cnt FROM messages WHERE thread_parent_id IN ("
                + placeholders + ") GROUP BY thread_parent_id";
        try (PreparedStatement ps = conn.prepareStatement(sql)) {
            int idx = 1;
            for (Long id : byId.keySet()) {
                ps.setLong(idx++, id);
            }
            try (ResultSet rs = ps.executeQuery()) {
                while (rs.next()) {
                    long parentId = rs.getLong("thread_parent_id");
                    int cnt = rs.getInt("cnt");
                    Message parent = byId.get(parentId);
                    if (parent != null && cnt > 0) {
                        parent.setThreadReplyCount(cnt);
                    }
                }
            }
        }
    }

    private Integer countThreadReplies(Connection conn, Long parentId) throws SQLException {
        if (parentId == null) return null;
        try (PreparedStatement ps = conn.prepareStatement("SELECT COUNT(*) FROM messages WHERE thread_parent_id = ?")) {
            ps.setLong(1, parentId);
            try (ResultSet rs = ps.executeQuery()) {
                if (rs.next()) {
                    int cnt = rs.getInt(1);
                    return cnt > 0 ? cnt : null;
                }
            }
        }
        return null;
    }

    private Message mapMessage(ResultSet rs) throws SQLException {
        Message m = new Message();
        m.setId(rs.getLong("id"));
        m.setTempId(rs.getString("temp_id"));
        m.setType(MessageType.valueOf(rs.getString("msg_type")));
        m.setChannel(rs.getString("channel"));
        m.setSender(rs.getString("sender"));
        m.setTarget(rs.getString("target"));
        m.setContent(rs.getString("content"));

        long replyTo = rs.getLong("reply_to_id");
        if (!rs.wasNull()) m.setReplyToId(replyTo);
        m.setReplySender(rs.getString("reply_sender"));
        m.setReplyPreview(rs.getString("reply_preview"));

        long threadParent = rs.getLong("thread_parent_id");
        if (!rs.wasNull()) m.setThreadParentId(threadParent);

        m.setReactions(fromJsonOrNull(rs.getString("reactions_json"), new TypeReference<>() {}));
        m.setEmbed(fromJsonOrNull(rs.getString("embed_json"), EmbedData.class));
        m.setPoll(fromJsonOrNull(rs.getString("poll_json"), PollData.class));
        m.setAttachmentName(rs.getString("attachment_name"));
        m.setAttachmentBase64(rs.getString("attachment_base64"));

        boolean enc = rs.getBoolean("encrypted");
        if (enc) m.setEncrypted(true);
        m.setIv(rs.getString("iv"));
        m.setSenderPublicKey(rs.getString("sender_public_key"));
        m.setTimestamp(rs.getLong("created_at"));
        return m;
    }

