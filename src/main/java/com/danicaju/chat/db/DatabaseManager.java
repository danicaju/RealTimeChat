    public Message insertMessage(Message msg) {
        if (msg == null || msg.getType() == null) {
            return msg;
        }
        long ts = msg.getTimestamp() > 0 ? msg.getTimestamp() : Instant.now().toEpochMilli();
        msg.setTimestamp(ts);

        String sql = """
            INSERT INTO messages (
                temp_id, msg_type, channel, sender, target, content,
                reply_to_id, reply_sender, reply_preview, thread_parent_id,
                reactions_json, embed_json, poll_json,
                attachment_name, attachment_base64,
                encrypted, iv, sender_public_key, created_at
            ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
        """;

        try (Connection conn = pool.getConnection();
             PreparedStatement ps = conn.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS)) {
            ps.setString(1, msg.getTempId());
            ps.setString(2, msg.getType().name());
            ps.setString(3, msg.getChannel());
            ps.setString(4, msg.getSender());
            ps.setString(5, msg.getTarget());
            ps.setString(6, msg.getContent());
            if (msg.getReplyToId() != null) ps.setLong(7, msg.getReplyToId()); else ps.setNull(7, Types.BIGINT);
            ps.setString(8, msg.getReplySender());
            ps.setString(9, msg.getReplyPreview());
            if (msg.getThreadParentId() != null) ps.setLong(10, msg.getThreadParentId()); else ps.setNull(10, Types.BIGINT);
            ps.setString(11, toJsonOrNull(msg.getReactions()));
            ps.setString(12, toJsonOrNull(msg.getEmbed()));
            ps.setString(13, toJsonOrNull(msg.getPoll()));
            ps.setString(14, msg.getAttachmentName());
            ps.setString(15, msg.getAttachmentBase64());
            ps.setBoolean(16, Boolean.TRUE.equals(msg.getEncrypted()));
            ps.setString(17, msg.getIv());
            ps.setString(18, msg.getSenderPublicKey());
            ps.setLong(19, ts);

            ps.executeUpdate();
            try (ResultSet keys = ps.getGeneratedKeys()) {
                if (keys.next()) {
                    msg.setId(keys.getLong(1));
                }
            }
            return msg;
        } catch (SQLException e) {
            throw new IllegalStateException("Error insertando mensaje en H2", e);
        }
    }

    public Message getMessageById(long id) {
        String sql = "SELECT * FROM messages WHERE id = ?";
        try (Connection conn = pool.getConnection(); PreparedStatement ps = conn.prepareStatement(sql)) {
            ps.setLong(1, id);
            try (ResultSet rs = ps.executeQuery()) {
                if (rs.next()) {
                    Message m = mapMessage(rs);
                    m.setThreadReplyCount(countThreadReplies(conn, m.getId()));
                    return m;
                }
            }
            return null;
        } catch (SQLException e) {
            throw new IllegalStateException("Error consultando mensaje por id", e);
        }
    }

    /**
     * Paginación estrictamente por cursores (beforeId / afterId + LIMIT) sin usar OFFSET.
     */
    public CursorPage getMessagesCursor(String channel, Long beforeId, Long afterId, int limit) {
        int safeLimit = Math.max(1, Math.min(limit, 100));
        int fetchLimit = safeLimit + 1;
        List<Message> rows = new ArrayList<>();

        try (Connection conn = pool.getConnection()) {
            PreparedStatement ps;
            boolean reverseOrder = false;
            if (afterId != null && afterId > 0) {
                ps = conn.prepareStatement("""
                    SELECT * FROM messages
                    WHERE LOWER(channel) = LOWER(?) AND thread_parent_id IS NULL AND id > ?
                    ORDER BY id ASC LIMIT ?
                """);
                ps.setString(1, channel);
                ps.setLong(2, afterId);
                ps.setInt(3, fetchLimit);
            } else if (beforeId != null && beforeId > 0) {
                reverseOrder = true;
                ps = conn.prepareStatement("""
                    SELECT * FROM messages
                    WHERE LOWER(channel) = LOWER(?) AND thread_parent_id IS NULL AND id < ?
                    ORDER BY id DESC LIMIT ?
                """);
                ps.setString(1, channel);
                ps.setLong(2, beforeId);
                ps.setInt(3, fetchLimit);
            } else {
                reverseOrder = true;
                ps = conn.prepareStatement("""
                    SELECT * FROM messages
                    WHERE LOWER(channel) = LOWER(?) AND thread_parent_id IS NULL
                    ORDER BY id DESC LIMIT ?
                """);
                ps.setString(1, channel);
                ps.setInt(2, fetchLimit);
            }

            try (ps; ResultSet rs = ps.executeQuery()) {
                while (rs.next()) {
                    rows.add(mapMessage(rs));
                }
            }

            boolean hasMore = rows.size() > safeLimit;
            if (hasMore) {
                rows = new ArrayList<>(rows.subList(0, safeLimit));
            }
            if (reverseOrder) {
                Collections.reverse(rows);
            }

            populateThreadCounts(conn, rows);
            return new CursorPage(rows, hasMore);
        } catch (SQLException e) {
            throw new IllegalStateException("Error en paginación por cursores", e);
        }
    }

