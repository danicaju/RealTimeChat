    public int countAdminUsers() {
        String sql = "SELECT role, permissions FROM user_profiles";
        int count = 0;
        try (Connection conn = pool.getConnection();
             Statement st = conn.createStatement();
             ResultSet rs = st.executeQuery(sql)) {
            while (rs.next()) {
                String role = rs.getString("role");
                long perms = rs.getLong("permissions");
                if (Permission.ROLE_ADMIN.equalsIgnoreCase(role)
                        || Permission.hasPermission(perms, Permission.ADMINISTRATOR)) {
                    count++;
                }
            }
            return count;
        } catch (SQLException e) {
            throw new IllegalStateException("Error contando administradores", e);
        }
    }

